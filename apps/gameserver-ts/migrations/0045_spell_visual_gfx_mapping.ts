export async function up(db: Kysely<never>): Promise<void> {
  const pairs = MAPPING.split(",").map((entry) => {
    const [id, gfx] = entry.split(":").map(Number);
    return { id: id as number, gfx: gfx as number };
  });

  const chunkSize = 500;
  for (let i = 0; i < pairs.length; i += chunkSize) {
    const values = sql.join(
      pairs
        .slice(i, i + chunkSize)
        .map(({ id, gfx }) => sql`(${id}::int, ${gfx}::int)`),
      sql`, `
    );
    await sql`
      WITH mapping(spell_id, gfx) AS (VALUES ${values})
      UPDATE spell_levels sl
      SET visual_gfx_id = mapping.gfx
      FROM mapping
      WHERE sl.spell_id = mapping.spell_id
    `.execute(db);
  }
}

